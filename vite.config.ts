import { fileURLToPath } from "node:url";

import tailwindcss from "@tailwindcss/vite";
import react from "@vitejs/plugin-react";
import { defineConfig, mergeConfig, type Plugin, type Rolldown, type UserConfig } from "vite";

import { BOOT_READS } from "./web/src/api/bootReads.ts";

/**
 * The SPA build.
 *
 * `root: 'web'` makes web/index.html the entry. `base: '/'` because the shell is
 * served from the document root, unlike the old per-page bundles which were
 * served from /assets/dist/.
 *
 * outDir is dist/build/ — the deploy artifact — because tools/build.mjs copies
 * the Laravel API in beside this output afterwards. dist/build/ is git-ignored
 * and fully regenerated by whichever build ran last, and tools/build.mjs starts
 * by removing it, so the two builds cannot corrupt each other.
 *
 * The dev server proxies /api and /sanctum to the `web` container, so the
 * browser sees ONE origin on :5173. That is not a convenience — Sanctum's
 * stateful SPA flow authenticates by cookie, and a cross-origin dev setup would
 * need CORS plus SameSite handling that production does not have, i.e. it would
 * stop testing the real thing. The dev origin is listed in
 * SANCTUM_STATEFUL_DOMAINS in docker/api/env.docker only, never in a shipped
 * default.
 *
 * changeOrigin stays false: Sanctum matches the request's Host against
 * SANCTUM_STATEFUL_DOMAINS, so rewriting it to the target would defeat the
 * entry we just added for :5173.
 */
/**
 * Where the dev server forwards /api and /sanctum.
 *
 * Defaults to the published port, which is right when `npm run dev:web` runs on
 * the host. Inside the compose stack the dev server runs in the `assets`
 * container, where localhost is that container and not the site — so
 * docker-compose.yml sets this to the `web` service by name. Without it the
 * proxy answers 502 for every API call and the SPA looks broken with no clue
 * why.
 */
const apiProxyTarget = process.env.VITE_API_PROXY_TARGET ?? "http://localhost:8090";

/**
 * A PR preview: `vite build --mode preview`, run by tools/build-preview.mjs
 * and .github/workflows/preview.yml (#353).
 *
 * The SPA with the mocked backend bundled in, served from
 * https://hoferan.github.io/website-les-canetons/pr-<n>/. That subpath is the
 * base, so the hashed bundles resolve and BASE_URL tells the app where it is
 * mounted. Built into dist/preview/ so it never touches the deploy artifact.
 * And kept out of search engines: it is public, and its data is made up.
 */
function previewMode(): UserConfig {
  const pr = process.env.VITE_PREVIEW_PR ?? "";
  if (!/^[1-9]\d*$/.test(pr)) {
    throw new Error(`--mode preview needs VITE_PREVIEW_PR set to a PR number, got "${pr}".`);
  }

  const shell: Plugin = {
    name: "preview-shell",
    transformIndexHtml: () => [
      { tag: "meta", attrs: { name: "robots", content: "noindex" }, injectTo: "head" },
      // Pages has no rewrite rules and serves 404.html from the site root
      // only. That page, config/preview-pages/404.html, sends a deep link
      // such as pr-<n>/de/agenda to pr-<n>/?__path=/de/agenda. This puts the
      // path back before the app's module script reads it: a module script
      // runs only once the document is parsed, this runs where it stands.
      {
        tag: "script",
        children:
          "(function(){var q=new URLSearchParams(location.search),p=q.get('__path');" +
          "if(p===null)return;q.delete('__path');var s=q.toString();" +
          "history.replaceState(null,'',location.pathname.replace(/\\/$/,'')+p+(s?'?'+s:'')+location.hash)})()",
        injectTo: "head",
      },
    ],
  };

  return {
    base: `/website-les-canetons/pr-${pr}/`,
    plugins: [shell],
    build: { outDir: "../dist/preview" },
  };
}

/**
 * The boot reads, preloaded by the shell so they travel while the bundle
 * downloads (web/src/api/bootReads.ts).
 *
 * The production build only. The dev server's /api may be a proxy to nothing
 * (`npm run dev:mock`), and a PR preview has no API at all: its service worker
 * answers, and only once the bundle has started it.
 *
 * crossorigin="use-credentials" because the app fetches with credentials:
 * "include", and a preload is used only by a request in the same mode. The
 * API answers JSON on /api/* whatever the Accept header says, so the
 * preload's generic Accept gets the same answer the app's own request would.
 */
function bootPreloads(): Plugin {
  return {
    name: "boot-preloads",
    apply: (_, { command, mode }) => command === "build" && mode !== "preview",
    transformIndexHtml: () =>
      BOOT_READS.map((href) => ({
        tag: "link",
        attrs: { rel: "preload", href, as: "fetch", crossorigin: "use-credentials" },
        injectTo: "head",
      })),
  };
}

/** The SPA's entry module, the root of what every visitor downloads. */
const ENTRY = fileURLToPath(new URL("./web/src/main.tsx", import.meta.url));

/** A module id as rolldown spells it on any platform. */
const normalized = (id: string) => id.replace(/\\/g, "/");

/**
 * Every module the entry imports statically, in one chunk (#396).
 *
 * The members' pages and the editors are loaded on demand (routes.tsx,
 * lib/lazy.tsx), and each shares modules with the entry. Left alone,
 * rolldown cuts every such set of shared modules into a chunk of its own: a
 * public page then fetches seventeen scripts, and on a slow phone the extra
 * requests cost more than the splitting saves. With this group a lazy chunk
 * imports from the one chunk the visitor already has.
 */
function visitorChunk(): (id: string, ctx: Rolldown.ChunkingContext) => string | null {
  let visitor: Set<string> | undefined;

  return (id, ctx) => {
    if (visitor === undefined) {
      visitor = new Set();
      const queue = [ENTRY];
      for (const next of queue) {
        const key = normalized(next);
        if (visitor.has(key)) continue;
        visitor.add(key);
        queue.push(...(ctx.getModuleInfo(next)?.importedIds ?? []));
      }
    }
    return visitor.has(normalized(id)) ? "visitor" : null;
  };
}

const config: UserConfig = {
  root: "web",
  base: "/",
  plugins: [react(), tailwindcss(), bootPreloads()],
  // `@/` -> web/src. Note root is "web" below, so this is resolved from the
  // REPO root and not from the Vite root. It must agree with tsconfig.json's
  // paths and with vitest.config.ts, which is a separate config file in this
  // project -- see its own comment.
  resolve: {
    alias: {
      // `@ds` before `@`: the alias list is matched in order and "@" is a prefix of it.
      "@ds": fileURLToPath(new URL("./web/src/design-system", import.meta.url)),
      "@": fileURLToPath(new URL("./web/src", import.meta.url)),
    },
  },
  build: {
    outDir: "../dist/build",
    emptyOutDir: true,
    sourcemap: false,
    rolldownOptions: {
      output: { codeSplitting: { groups: [{ name: visitorChunk() }] } },
    },
  },
  server: {
    // PORT, when something upstream assigns one.
    //
    // Vite does not read PORT on its own: left alone it takes 5173, which the
    // compose `assets` container already publishes. That is fine for the main
    // checkout and wrong in a git worktree, where :5173 serves the OTHER tree's
    // web/ and a preview shows code that is not the code you are editing.
    // Honouring PORT is what lets each worktree run a dev server of its own on
    // whatever port is free.
    //
    // strictPort only when PORT was assigned: a caller that named a port needs
    // the server on THAT port or nowhere, because it is about to open it.
    // Vite's own default behaviour — drift to the next free port — is right
    // when nobody asked for one.
    //
    // The Playwright harness passes `--port 5174 --strictPort` on the command
    // line instead, which outranks this; see playwright.config.ts for why it
    // owns a port of its own.
    port: process.env.PORT ? Number(process.env.PORT) : undefined,
    strictPort: process.env.PORT !== undefined,
    proxy: {
      "/api": { target: apiProxyTarget, changeOrigin: false },
      "/sanctum": { target: apiProxyTarget, changeOrigin: false },
    },
    // Filesystem events do not cross a Docker Desktop bind mount reliably on
    // Windows or macOS, so the dev server inside the `assets` container simply
    // never notices an edit — the page keeps serving the previous version and
    // the only fix looks like "restart the container", which nobody guesses.
    // Polling is the standard workaround; it costs CPU, so it is opt-in and
    // docker-compose.yml turns it on for that container alone.
    watch: process.env.VITE_USE_POLLING === "1" ? { usePolling: true, interval: 300 } : undefined,
  },
};

export default defineConfig(({ mode }) =>
  mergeConfig(config, mode === "preview" ? previewMode() : {}),
);
